def _build_minor() -> list:
    deck = []
    for suit, suit_theme in SUITS:
        for rank, meaning in RANKS:
            name = f"{suit}{rank}"
            upright = f"{suit_theme}方面的提示：{meaning}"
            reversed_ = f"{suit_theme}方面有些卡顿，调整一下状态。"
            deck.append((name, upright, reversed_))
    return deck


